_INDEX: Final[dict[tuple[str, str, str], Endpoint]] = {
    (endpoint.host, endpoint.path, endpoint.method): endpoint for endpoint in ENDPOINTS
}
if len(_INDEX) != len(ENDPOINTS):
    raise RuntimeError("Duplicate endpoint catalog key")


def get_endpoint(
    path: str,
    *,
    method: str = "GET",
    host: str = PRODUCTION_HOST,
) -> Endpoint:
    try:
        return _INDEX[(host, path, method.upper())]
    except KeyError:
        raise KeyError(
            f"Endpoint is not cataloged: {method.upper()} {host}{path}"
        ) from None


def catalog_rows() -> list[dict[str, object]]:
    """Return deterministic, secret-free rows for CSV/XLSX catalog export."""

    rows: list[dict[str, object]] = []
    for endpoint in sorted(
        ENDPOINTS, key=lambda ep: (ep.family, ep.host, ep.path, ep.method)
    ):
        row = asdict(endpoint)
        row["allowed_params"] = ",".join(sorted(endpoint.allowed_params))
        row["required_params"] = ",".join(sorted(endpoint.required_params))
        rows.append(row)
    return rows
