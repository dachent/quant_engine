"""Auditable endpoint inventory and semantic read-only allowlist.

The catalog intentionally includes excluded mutation endpoints and endpoints
belonging to other credential/host families.  Inclusion in the catalog does not
grant network access: only ``live_enabled`` GET endpoints on ``PRODUCTION_HOST``
can pass the transport policy.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Final, Iterable


