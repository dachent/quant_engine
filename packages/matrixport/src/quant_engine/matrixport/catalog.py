COVERAGE_STATUSES: Final[frozenset[str]] = frozenset(
    {
        "complete_to_observed_boundary",
        "partial",
        "unsupported",
        "permission_denied",
        "documented_unverified",
        "excluded_mutation",
        "not_applicable",
    }
)


@dataclass(frozen=True, slots=True)
class Endpoint:
    family: str
    name: str
    method: str
    host: str
    path: str
    allowed_params: frozenset[str]
    required_params: frozenset[str]
    authentication: str
    pagination: str
    output_table: str
    source_url: str
    safety_class: str
    disposition: str
    live_enabled: bool = False
    note: str = ""

    def __post_init__(self) -> None:
        if self.method not in {"GET", "POST", "PUT"}:
            raise ValueError(f"unsupported catalog method: {self.method}")
        if not self.path.startswith("/"):
            raise ValueError(f"catalog path must be absolute: {self.path}")
        if not self.required_params <= self.allowed_params:
            raise ValueError(f"required params are not allowlisted: {self.name}")
        if self.disposition not in COVERAGE_STATUSES:
            raise ValueError(f"invalid catalog disposition: {self.disposition}")
        if self.live_enabled and (
            self.method != "GET"
            or self.host != PRODUCTION_HOST
            or self.safety_class != "read_only"
        ):
            raise ValueError(f"unsafe endpoint cannot be live-enabled: {self.name}")


def _ep(
    family: str,
    name: str,
    method: str,
    path: str,
    params: Iterable[str] = (),
    required: Iterable[str] = (),
    *,
    auth: str = "v2",
    pagination: str = "none",
    table: str = "",
    source: str,
    safety: str = "read_only",
    disposition: str = "complete_to_observed_boundary",
    live: bool = False,
    host: str = PRODUCTION_HOST,
    note: str = "",
) -> Endpoint:
    return Endpoint(
        family=family,
        name=name,
        method=method,
        host=host,
        path=path,
        allowed_params=frozenset(params),
        required_params=frozenset(required),
        authentication=auth,
        pagination=pagination,
        output_table=table,
        source_url=source,
        safety_class=safety,
        disposition=disposition,
        live_enabled=live,
        note=note,
    )


